-- 0340_a_hundred_and_sixty_six_gu_in_the_dark
--
-- The Gu of Black Heaven. A hundred and fifty-one of them are new; fifteen
-- were already in the game - Belief Gu, Lifespan Gu, Moonlight Gu and the
-- rest - and those are linked rather than duplicated, because a second
-- Moonlight Gu with a different id is two things the player cannot tell apart
-- and the refinery certainly cannot.
--
-- THE HUNDRED AND FIFTY-ONE ARE DERIVED, NOT TYPED. The names are systematic:
-- a family word and then an action word. So the family decides the Path and
-- the rank, and the action decides what the Gu is for:
--
--     Celestial / Heavenly / Heaven / Divine   heaven, rank 8
--     Sky                                      heaven, rank 7
--     Moon / Lunar / Crescent / Waning         light,  rank 7
--     Human / Man / Flesh                      human,  rank 6
--     Mortal / Common / Hundred Men            human,  rank 5
--
--     Blade, Strike, Fang, Wrath, Fall         attack
--     Guard, Wall, Shield, Veil, Skin          defense
--     Step, Leap, Sense, Vision, Calculation   utility
--     Essence, Lifespan, Rebirth, Phase        cultivation
--     everything else                          support
--
-- A rule reproduces a hundred and fifty-one rows exactly; a hand does not,
-- and a hand that slips on row ninety leaves a Gu whose Path disagrees with
-- its name for as long as the game runs.
--
-- SIZE, RARITY AND MAGNITUDE FOLLOW THE HOUSE STYLE rather than inventing
-- one. Every Gu in this game has size = rank and a rarity fixed by rank -
-- rank 8 is unique, 7 divine, 6 mythic, 5 legendary - and carries two
-- effects whose magnitudes were read off the live averages at each rank. A
-- small deterministic wobble keeps a family from reading as fifteen copies
-- of one row without making any of them an outlier.
--
-- THE DROP WEIGHTS FALL WITH THE RANK, so the dark mostly gives up Human and
-- Mortal Gu and a Celestial one is worth the walk.
--
-- Forward-only. Do not edit once applied.


