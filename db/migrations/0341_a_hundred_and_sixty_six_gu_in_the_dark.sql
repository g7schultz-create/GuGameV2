DO $probe$
DECLARE
    n   INTEGER;
    bad TEXT;
BEGIN
    SELECT count(*) INTO n FROM gu_region_drops WHERE region_code = 'black_heaven';
    IF n <> 166 THEN
        RAISE EXCEPTION 'expected 166 Gu in Black Heaven, linked %', n;
    END IF;

    -- A Gu with no effect is a bug in a jar. Only the new ones are this
    -- migration's business - the fifteen that were already here have whatever
    -- they shipped with.
    SELECT string_agg(g.name, ', ') INTO bad
    FROM gu_types g
    WHERE g.description = 'Found only in Black Heaven.'
      AND NOT EXISTS (SELECT 1 FROM gu_type_effects ef
                      WHERE ef.gu_type_id = g.gu_type_id);
    IF bad IS NOT NULL THEN
        RAISE EXCEPTION 'these do nothing: %', bad;
    END IF;

    -- Size is rank, the way every other Gu in the game has it.
    SELECT string_agg(g.name, ', ') INTO bad
    FROM gu_types g
    WHERE g.description = 'Found only in Black Heaven.' AND g.size <> g.rank;
    IF bad IS NOT NULL THEN
        RAISE EXCEPTION 'these are the wrong size for their rank: %', bad;
    END IF;

    RAISE NOTICE 'one hundred and sixty-six Gu are found in Black Heaven';
END;
