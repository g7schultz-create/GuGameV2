DO $$
DECLARE
    n BIGINT;
BEGIN
    -- Ranks 1 to 3 were left alone, which is the half of the ask that is easy
    -- to break by writing the range wrong.
    SELECT count(*) INTO n FROM gu_types t
    WHERE t.rank <= 3
      AND (SELECT count(*) FROM gu_type_effects e
           WHERE e.gu_type_id = t.gu_type_id) > 2;
    IF n > 0 THEN
        RAISE EXCEPTION '% Gu below rank 4 were given a third word', n;
    END IF;

    -- And nothing at rank 4 or 5 is left saying one thing.
    SELECT count(*) INTO n FROM gu_types t
    WHERE t.rank IN (4, 5)
      AND (SELECT count(*) FROM gu_type_effects e
           WHERE e.gu_type_id = t.gu_type_id) < 2;
    IF n > 0 THEN
        RAISE EXCEPTION '% Gu at rank 4 or 5 still lend only one thing', n;
    END IF;

    -- No Gu says the same word twice; the primary key already forbids it, so
    -- this is really asking whether any pairing was a rename of its partner.
    SELECT count(*) INTO n FROM (
        SELECT e.gu_type_id FROM gu_type_effects e
        GROUP BY e.gu_type_id
        HAVING count(*) <> count(DISTINCT e.effect_code)
    ) s;
    IF n > 0 THEN
        RAISE EXCEPTION '% Gu repeat themselves', n;
    END IF;

    -- Still nobody finishing a ceiling alone.
    SELECT count(*) INTO n FROM gu_type_effects e
    JOIN gu_effects f ON f.code = e.effect_code
    WHERE e.magnitude > 0.6 * f.cap;
    IF n > 0 THEN
        RAISE EXCEPTION '% magnitudes eat more than three fifths of a cap', n;
    END IF;

    -- Every live word now has Gu behind it. A word the catalogue never speaks
    -- is a promise on the /gu screen that nothing can keep.
    SELECT count(*) INTO n FROM gu_effects f
    WHERE f.is_live
      AND NOT EXISTS (SELECT 1 FROM gu_type_effects e WHERE e.effect_code = f.code);
    IF n > 0 THEN
        RAISE EXCEPTION '% live effects have no Gu behind them', n;
    END IF;

    -- And each of the six build axes the design names is held up by more than
    -- a handful, which multi_hit was not.
    SELECT count(*) INTO n FROM (VALUES
        ('multi_hit'), ('attack_power'), ('dodge'),
        ('armor_pen'), ('crit_rate'), ('lifesteal')
    ) AS axis(code)
    WHERE (SELECT count(*) FROM gu_type_effects e
           WHERE e.effect_code = axis.code) < 10;
    IF n > 0 THEN
        RAISE EXCEPTION '% build axes are held up by fewer than ten Gu', n;
    END IF;
END;
$$;
