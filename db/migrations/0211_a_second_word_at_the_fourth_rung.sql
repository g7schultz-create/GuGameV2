-- 0211_a_second_word_at_the_fourth_rung
--
-- 0209 gave every Gu in the catalogue a capped effect, and gave a second one
-- only where the Gu's Path said something its first word had not already said.
-- For an attack Gu that nearly always fires - 97% of them carry two. For a
-- support Gu the Path effect IS the first word, so there was nothing left to
-- add and 83% of them carry one.
--
-- One word is right for a rank 1 worm. It is thin at rank 4, where a Gu costs
-- four of an aperture that holds six or seven: the price of a whole slot ought
-- to buy more than a single number.
--
-- So ranks 1 to 3 keep saying one thing, and the 508 Gu at ranks 4 and 5 that
-- only said one now say two.
--
-- A COMPANION IS ON A DIFFERENT AXIS. Pairing Braced with Damage Reduction
-- would be one idea written twice and would let a single Gu decide a fight the
-- caps exist to keep open. Tempering pairs with a bigger body; evasion with
-- tempo; seeing the opening with taking it. Where the axis left a choice, it
-- went to the effect with the fewest Gu behind it.
--
-- FIVE EFFECTS HAD NOTHING BEHIND THEM. `death_ward`, `gu_potency`,
-- `pill_potency`, `realm_foundation` and `refine_conflict_relief` were live
-- words the whole catalogue never spoke, and `multi_hit` was down to the three
-- Gu 0036 shipped - one of the six build axes the design names, held up by
-- three worms. Six sources are aimed at them, one each, and each pairing has
-- to read true on its own: seeing pairs with reading worms, a deep qi pool
-- with still being on your feet, healing with what medicine does to a body.
--
-- THE SECOND WORD IS SMALLER, at 55% of what the first would have been at that
-- rank - the same share 0209 used - and still under three fifths of its cap.
-- Nothing here can finish an effect on its own.
--
-- No Gu changes what it already said. Nothing anybody owns is touched; a Gu
-- already in an aperture simply lends one more thing.
--
-- Forward-only. Do not edit once applied.


